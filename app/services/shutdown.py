import asyncio
import logging
import os
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path

import asyncssh
from sqlalchemy.orm import Session, sessionmaker

from app.db.models import ActionLog, Device
from app.i18n import N_, detail_text, gettext

log = logging.getLogger(__name__)

OK, ERROR = "ok", "error"
# Outcomes of Shutdowner.shutdown besides OK / ERROR.
DISABLED, BUSY = "disabled", "busy"

OS_NAMES = {"windows": "Windows", "linux": "Linux", "macos": "macOS"}
COMMANDS = {
    "windows": "shutdown /s /t 0",
    "linux": "sudo -n shutdown -h now",
    "macos": "sudo -n shutdown -h now",
}
SSH_PORT = 22


def load_or_create_key(path: Path) -> asyncssh.SSHKey:
    """The app's ed25519 key; generated once in the data directory."""
    if path.exists():
        return asyncssh.read_private_key(path)
    key = asyncssh.generate_private_key("ssh-ed25519", comment="lanmon")
    path.write_bytes(key.export_private_key())
    os.chmod(path, 0o600)
    return key


def key_fingerprint(key: asyncssh.SSHKey) -> str:
    """Type + data, without the comment, so host keys compare exactly."""
    return " ".join(key.export_public_key().decode().split()[:2])


@dataclass(frozen=True)
class ShutdownResult:
    status: str  # ok / error / disabled / busy
    name: str | None = None
    # English; stored in the log and translated on display (see app.i18n.detail_text).
    detail: str | None = None

    @property
    def ok(self) -> bool:
        return self.status == OK


@dataclass(frozen=True)
class ShutdownTarget:
    id: int
    name: str
    ip: str | None
    user: str | None
    os: str | None
    host_key: str | None


class _Client(asyncssh.SSHClient):
    """Trust on first use: the first host key is remembered and must not change afterwards."""

    def __init__(self, expected: str | None) -> None:
        self.expected = expected
        self.seen: str | None = None

    def validate_host_public_key(self, host, addr, port, key) -> bool:
        self.seen = key_fingerprint(key)
        return self.expected is None or self.seen == self.expected


class Shutdowner:
    """Shuts devices down over SSH with the key generated by the app."""

    def __init__(
        self,
        session_factory: sessionmaker[Session],
        key_path: Path,
        port: int = SSH_PORT,
        timeout: float = 10,
    ) -> None:
        self._session_factory = session_factory
        self._key_path = key_path
        self._key: asyncssh.SSHKey | None = None
        self.port = port
        self.timeout = timeout
        self.pending: set[int] = set()

    @property
    def key(self) -> asyncssh.SSHKey:
        if self._key is None:
            self._key = load_or_create_key(self._key_path)
        return self._key

    def public_key(self) -> str:
        return self.key.export_public_key().decode().strip()

    async def shutdown(self, device_id: int, source: str = "user") -> ShutdownResult:
        """Sends the shutdown command and records it in the log."""
        target = await asyncio.to_thread(self._load, device_id)
        if target is None:
            return ShutdownResult(DISABLED)
        if target.id in self.pending:
            return ShutdownResult(BUSY, target.name)
        self.pending.add(target.id)
        try:
            ok, detail, seen = await self._run(target)
        finally:
            self.pending.discard(target.id)
        await asyncio.to_thread(self._record, target, source, ok, detail, seen)
        return ShutdownResult(OK if ok else ERROR, target.name, detail)

    def _load(self, device_id: int) -> ShutdownTarget | None:
        with self._session_factory() as session:
            device = session.get(Device, device_id)
            if device is None or not device.shutdown_enabled:
                return None
            return ShutdownTarget(
                device.id,
                device.name,
                device.last_ip,
                device.ssh_user,
                device.os,
                device.ssh_host_key,
            )

    async def _run(self, target: ShutdownTarget) -> tuple[bool, str | None, str | None]:
        """(succeeded, detail, host key seen)."""
        if not target.ip:
            return False, N_("No known IP address."), None
        if not target.user or target.os not in COMMANDS:
            return False, N_("The SSH user or the operating system is missing."), None
        client = _Client(target.host_key)
        try:
            key = await asyncio.to_thread(lambda: self.key)
            async with asyncssh.connect(
                target.ip,
                port=self.port,
                username=target.user,
                client_keys=[key],
                client_factory=lambda: client,
                known_hosts=([], [], []),
                agent_path=None,
                config=[],
                preferred_auth="publickey",
                connect_timeout=self.timeout,
            ) as conn:
                try:
                    result = await conn.run(COMMANDS[target.os], check=False, timeout=self.timeout)
                except (asyncssh.ConnectionLost, asyncssh.DisconnectError):
                    # The system closed the connection because it is shutting down.
                    return True, None, client.seen
                except TimeoutError:
                    return (
                        True,
                        N_("The command didn't answer; it's probably shutting down."),
                        client.seen,
                    )
        except (asyncssh.HostKeyNotVerifiable, asyncssh.KeyExchangeFailed):
            if target.host_key and client.seen and client.seen != target.host_key:
                reason = N_(
                    "The SSH host key changed from the remembered one. If the system was "
                    "reinstalled, forget the host key on the device page."
                )
                return False, reason, None
            return False, N_("The SSH connection was refused while checking the host key."), None
        except asyncssh.PermissionDenied:
            reason = N_("The app's key isn't accepted (see Settings → Remote shutdown).")
            return False, reason, None
        except TimeoutError:
            return False, f"{N_('No answer on the SSH port')}: {self.port}", None
        except (OSError, asyncssh.Error) as exc:
            raw = str(exc) or type(exc).__name__
            return False, f"{N_('The SSH connection failed')}: {raw}", None
        if result.exit_status in (0, None):
            return True, None, client.seen
        message = str(result.stderr or result.stdout or "").strip().splitlines()
        reason = message[0] if message else f"exit code {result.exit_status}"
        return False, f"{N_('The command failed')}: {reason}", client.seen

    def _record(
        self,
        target: ShutdownTarget,
        source: str,
        ok: bool,
        detail: str | None,
        seen: str | None,
    ) -> None:
        now = datetime.now(UTC)
        with self._session_factory.begin() as session:
            session.add(
                ActionLog(
                    device_id=target.id,
                    action="shutdown",
                    source=source,
                    result=OK if ok else ERROR,
                    detail=detail,
                    created_at=now,
                    finished_at=now,
                )
            )
            device = session.get(Device, target.id)
            if device is not None and seen and device.ssh_host_key is None:
                device.ssh_host_key = seen
        log.info("Shutdown %s: %s %s", target.name, OK if ok else ERROR, detail or "")


def describe(lang: str, result: ShutdownResult) -> str:
    """The message shown to the user (or returned by the API) for a shutdown attempt."""
    if result.status == DISABLED:
        return gettext(lang, "The device doesn't have remote shutdown enabled.")
    if result.status == BUSY:
        return gettext(lang, "“{name}” is already shutting down.", name=result.name)
    if result.ok:
        return gettext(lang, "Sent the shutdown command to “{name}”.", name=result.name)
    reason = detail_text(lang, result.detail)
    return gettext(lang, "Couldn't shut down “{name}”: {reason}", name=result.name, reason=reason)
